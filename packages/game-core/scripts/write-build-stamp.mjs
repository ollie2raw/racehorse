// GC-1 (HARDENING_PLAN §7.3): runs as `postbuild`. Writes dist/buildStamp.data.js
// = { srcSha256, builtAt } so a consumer (the server, at boot) can prove the
// compiled dist/ it loaded was built from the committed src/.
//
// The hash contract is mirrored EXACTLY by server/src/platform/gameCoreConsistency.ts
// (hashGameCoreSrc): sorted top-level src/*.ts excluding *.test.ts, each
// contribution = filename + NUL + raw bytes + NUL.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const srcDir = join(pkgRoot, 'src');
const distDir = join(pkgRoot, 'dist');

const files = readdirSync(srcDir)
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))
  .sort();

const hash = createHash('sha256');
for (const file of files) {
  hash.update(file);
  hash.update('\0');
  hash.update(readFileSync(join(srcDir, file)));
  hash.update('\0');
}
const srcSha256 = hash.digest('hex');
const builtAt = new Date().toISOString();

writeFileSync(
  join(distDir, 'buildStamp.data.js'),
  `// Generated by scripts/write-build-stamp.mjs — do not edit.\n`
    + `module.exports = ${JSON.stringify({ srcSha256, builtAt }, null, 2)};\n`,
);

// eslint-disable-next-line no-console
console.log(`[game-core] build stamp ${srcSha256} @ ${builtAt} (${files.length} files)`);
